/**
 * 카테고리 ID -> 시드 키워드 목록 맵 생성 헬퍼
 */
export function buildCategorySeedMap(categories: TrendCategoryItem[] = DEFAULT_TREND_CATEGORIES): Record<string, string[]> {
  const map: Record<string, string[]> = {};
  categories.forEach((cat) => {
    if (cat.enabled !== false) {
      map[cat.id] = cat.seeds && cat.seeds.length > 0 ? cat.seeds : [cat.id];
    }
  });
  return map;
}

/**
 * 기본 시드 맵
 */
export const CATEGORIES_SEED_MAP: Record<string, string[]> = buildCategorySeedMap(DEFAULT_TREND_CATEGORIES);
